"""Randomized benchmarking (RB) for single-qubit gate error characterization.

Standard RB protocol:
1. Sample random sequences of Clifford gates of varying lengths
2. Append the inverse Clifford so the ideal result is |0>
3. Run each sequence and measure survival probability
4. Fit decay p(m) = A * alpha^m + B to extract depolarizing parameter alpha
5. Error per Clifford (EPC) = (1 - alpha) * (1 - 1/d) where d = 2^n_qubits

Reference: Magesan et al., PRL 106, 180504 (2011)
"""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np
from numpy.typing import NDArray

from ..core.circuit import QuantumCircuit
from ..core.gate import Gate, H, S, X, Y, Z


# Single-qubit Clifford group (24 elements)
# Generated by {H, S}: all single-qubit unitaries that map Paulis to Paulis
def _build_single_qubit_cliffords() -> list[NDArray[np.complexfloating]]:
    """Build the 24 single-qubit Clifford group matrices.

    Generates candidates by composing the generators {I, H, S, S^dag, X, Y, Z}
    up to depth 3, then de-duplicates up to global phase to obtain the 24
    unique single-qubit Clifford unitaries.

    Returns:
        A list of 24 unitary (2 x 2) complex NumPy arrays.
    """
    I = np.eye(2, dtype=complex)
    _X = X.matrix
    _Y = Y.matrix
    _Z = Z.matrix
    _H = H.matrix
    _S = S.matrix
    _Sd = S.matrix.conj().T  # S-dagger

    cliffords = []
    seen = set()

    generators = [I, _H, _S, _Sd, _X, _Y, _Z]
    # Build by composing up to depth 3
    candidates = list(generators)
    for g1 in generators:
        for g2 in generators:
            candidates.append(g1 @ g2)
            for g3 in generators:
                candidates.append(g1 @ g2 @ g3)

    for m in candidates:
        # Normalize global phase
        idx = np.argmax(np.abs(m.ravel()))
        phase = m.ravel()[idx]
        m_normalized = m * (abs(phase) / phase)
        key = tuple(np.round(m_normalized.ravel(), 6))
        if key not in seen:
            seen.add(key)
            cliffords.append(m)

    return cliffords[:24]


_CLIFFORDS = None


def _get_cliffords() -> list[NDArray[np.complexfloating]]:
    """Return the cached list of single-qubit Clifford matrices.

    Lazily builds the Clifford group on first call and caches the result
    in the module-level ``_CLIFFORDS`` variable.

    Returns:
        A list of 24 unitary (2 x 2) complex NumPy arrays.
    """
    global _CLIFFORDS
    if _CLIFFORDS is None:
        _CLIFFORDS = _build_single_qubit_cliffords()
    return _CLIFFORDS


def _compose_cliffords(
    indices: list[int],
    cliffords: list[NDArray[np.complexfloating]],
) -> NDArray[np.complexfloating]:
    """Compose a sequence of Clifford gates by matrix multiplication.

    Args:
        indices: List of indices into the ``cliffords`` list specifying
            the gate sequence (applied left to right).
        cliffords: The full list of Clifford matrices.

    Returns:
        The (2 x 2) unitary matrix representing the composed sequence.
    """
    result = np.eye(2, dtype=complex)
    for idx in indices:
        result = cliffords[idx] @ result
    return result


def _find_inverse_clifford(
    U: NDArray[np.complexfloating],
    cliffords: list[NDArray[np.complexfloating]],
) -> int:
    """Find the Clifford index whose matrix best inverts U.

    Searches the Clifford group for the element C that maximizes
    |Tr(C^dag U^dag)|^2 / d^2, which equals 1 when C = U^{-1}.

    Args:
        U: The unitary matrix to invert.
        cliffords: The full list of Clifford matrices.

    Returns:
        Index into ``cliffords`` of the best inverse Clifford.
    """
    U_dag = U.conj().T
    best_idx = 0
    best_fid = 0.0
    for i, C in enumerate(cliffords):
        fid = abs(np.trace(C.conj().T @ U_dag)) ** 2 / 4
        if fid > best_fid:
            best_fid = fid
            best_idx = i
    return best_idx


@dataclass
class RBResult:
    """Container for randomized benchmarking results.

    Attributes:
        sequence_lengths: List of Clifford sequence lengths tested.
        survival_probabilities: Mean survival probability at each sequence length.
        alpha: Depolarizing parameter from the exponential decay fit
            p(m) = A * alpha^m + B. Values close to 1 indicate low error.
        error_per_clifford: Error per Clifford gate, computed as
            (1 - alpha) * (1 - 1/d) where d is the Hilbert space dimension.
        offset_A: Amplitude parameter A from the exponential fit.
        offset_B: Offset parameter B from the exponential fit (ideally 1/d).
    """

    sequence_lengths: list[int]
    survival_probabilities: list[float]
    alpha: float
    error_per_clifford: float
    offset_A: float
    offset_B: float


def randomized_benchmarking(
    sequence_lengths: list[int] | None = None,
    num_samples: int = 20,
    noise_model: object | None = None,
    error_rate: float = 0.01,
    seed: int | None = None,
) -> RBResult:
    """Run single-qubit randomized benchmarking.

    Generates random Clifford sequences, appends the inverse, and
    measures survival probability. Optionally applies a simple
    depolarizing error to simulate noisy gates.

    Args:
        sequence_lengths: List of Clifford sequence lengths to test.
            Default: [1, 2, 4, 8, 16, 32, 64].
        num_samples: Number of random sequences per length.
        noise_model: Unused (reserved for future NoiseModel integration).
        error_rate: Per-gate depolarizing error probability (0 = perfect).
        seed: Random seed.

    Returns:
        RBResult with decay curve parameters and error per Clifford.
    """
    if sequence_lengths is None:
        sequence_lengths = [1, 2, 4, 8, 16, 32, 64]

    rng = np.random.default_rng(seed)
    cliffords = _get_cliffords()
    num_cliffords = len(cliffords)

    survival_probs = []

    for m in sequence_lengths:
        survivals = []
        for _ in range(num_samples):
            # Random Clifford sequence
            indices = rng.integers(0, num_cliffords, size=m).tolist()
            total_U = _compose_cliffords(indices, cliffords)

            # Append inverse
            inv_idx = _find_inverse_clifford(total_U, cliffords)
            indices.append(inv_idx)

            # Build circuit and apply with optional noise
            qc = QuantumCircuit(1)
            for idx in indices:
                gate = Gate(cliffords[idx], f"C{idx}")
                qc.apply(gate, 0)

            sv = qc.statevector()

            # Apply depolarizing noise model (analytical)
            # Each gate has probability error_rate of depolarizing
            # After m+1 gates, survival ≈ |<0|sv>|^2 * (1-error_rate)^(m+1)
            ideal_prob = float(abs(sv[0]) ** 2)
            noisy_prob = (
                ideal_prob * (1 - error_rate) ** (m + 1) + (1 - (1 - error_rate) ** (m + 1)) / 2
            )
            survivals.append(noisy_prob)

        survival_probs.append(float(np.mean(survivals)))

    # Fit exponential decay: p(m) = A * alpha^m + B
    # Use log-linear fit for alpha
    ms = np.array(sequence_lengths, dtype=float)
    ps = np.array(survival_probs)

    # Estimate B ≈ 1/d = 0.5 for single qubit
    B = 0.5
    ps_shifted = np.maximum(ps - B, 1e-12)
    log_ps = np.log(ps_shifted)

    if len(ms) >= 2:
        coeffs = np.polyfit(ms, log_ps, 1)
        alpha = float(np.exp(coeffs[0]))
        A = float(np.exp(coeffs[1]))
    else:
        alpha = 1.0 - error_rate
        A = 0.5

    alpha = min(max(alpha, 0.0), 1.0)
    epc = (1 - alpha) * (1 - 1 / 2)  # d=2 for single qubit

    return RBResult(
        sequence_lengths=sequence_lengths,
        survival_probabilities=survival_probs,
        alpha=alpha,
        error_per_clifford=epc,
        offset_A=A,
        offset_B=B,
    )
